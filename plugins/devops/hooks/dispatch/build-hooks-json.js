#!/usr/bin/env node
'use strict';
/**
 * @module dispatch/build-hooks-json
 * @version 0.1.0
 * @plugin devops
 * @description Generates hooks/hooks.json from hooks/dispatch/manifest.json:
 *   one dispatcher entry per event (`node dispatch.js <Event>`), its matcher
 *   the union of the event's module matchers (omitted when any module matches
 *   everything), its timeout the event budget (largest module timeout) plus
 *   the dispatcher's headroom. Modules with `"dispatch": false` keep their own
 *   entry, exactly as in the manifest. It also writes dispatch/lanes.json
 *   (dispatch/lanes.js: which modules may run in parallel).
 *
 *   CLI: node build-hooks-json.js          write hooks.json + lanes.json
 *        node build-hooks-json.js --check  exit 1 when either is stale
 */

const fs = require('fs');
const path = require('path');
const { unionMatcher } = require('./matcher');
const { computeLanes } = require('./lanes');
const { eventModules } = require('./dispatch');

const HOOKS_JSON = path.join(__dirname, '..', 'hooks.json');
const MANIFEST = path.join(__dirname, 'manifest.json');
const LANES_JSON = path.join(__dirname, 'lanes.json');
const PLUGIN_ROOT = path.resolve(__dirname, '..', '..');
const DEFAULT_TIMEOUT_S = 60;
const HEADROOM_S = 5;

function dispatcherCommand(event) {
  return `node "\${CLAUDE_PLUGIN_ROOT}/hooks/dispatch/dispatch.js" ${event}`;
}

/** @returns {object} the hooks.json object */
function build(manifest) {
  const hooks = {};
  for (const [event, groups] of Object.entries(manifest.hooks || {})) {
    const dispatched = [];
    const separate = [];
    for (const g of groups) {
      const keep = (g.hooks || []).filter((h) => h.dispatch === false);
      const disp = (g.hooks || []).filter((h) => h.dispatch !== false);
      if (keep.length) separate.push({ ...g, hooks: keep.map(({ dispatch: _dispatch, ...h }) => h) });
      for (const h of disp) dispatched.push({ matcher: g.matcher, timeout: typeof h.timeout === 'number' && h.timeout > 0 ? h.timeout : DEFAULT_TIMEOUT_S });
    }
    const entries = [];
    if (dispatched.length) {
      const budget = dispatched.reduce((m, d) => Math.max(m, d.timeout), 0);
      const entry = { hooks: [{ type: 'command', command: dispatcherCommand(event), timeout: budget + HEADROOM_S }] };
      const matcher = unionMatcher(dispatched.map((d) => d.matcher));
      if (matcher) entry.matcher = matcher;
      entries.push(entry);
    }
    entries.push(...separate);
    if (entries.length) hooks[event] = entries;
  }
  return { description: manifest.description, hooks };
}

/** hooks.json text: one hook object per line, like the hand-written file was. */
function serialize(obj) {
  const lines = ['{', `  "description": ${JSON.stringify(obj.description || '')},`, '  "hooks": {'];
  const events = Object.keys(obj.hooks);
  events.forEach((event, ei) => {
    lines.push(`    ${JSON.stringify(event)}: [`);
    obj.hooks[event].forEach((g, gi) => {
      lines.push('      {');
      const hs = g.hooks.map((h) => `          { ${Object.entries(h).map(([k, v]) => `${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(', ')} }`);
      lines.push('        "hooks": [');
      lines.push(hs.join(',\n'));
      lines.push(`        ]${g.matcher !== undefined ? ',' : ''}`);
      if (g.matcher !== undefined) lines.push(`        "matcher": ${JSON.stringify(g.matcher)}`);
      lines.push(`      }${gi < obj.hooks[event].length - 1 ? ',' : ''}`);
    });
    lines.push(`    ]${ei < events.length - 1 ? ',' : ''}`);
  });
  lines.push('  }', '}', '');
  return lines.join('\n');
}

function expectedText(manifestFile = MANIFEST) {
  return serialize(build(JSON.parse(fs.readFileSync(manifestFile, 'utf8'))));
}

/** lanes.json text: per event the lanes, plus the pid-tmp writers behind them. */
function expectedLanesText(manifestFile = MANIFEST, pluginRoot = PLUGIN_ROOT) {
  const manifest = JSON.parse(fs.readFileSync(manifestFile, 'utf8'));
  const lanes = {};
  const writers = {};
  for (const event of Object.keys(manifest.hooks || {})) {
    const mods = eventModules(manifest, event, pluginRoot).filter((m) => m.dispatch && m.isolate !== 'process');
    if (!mods.length) continue;
    const r = computeLanes(mods, pluginRoot);
    lanes[event] = r.lanes;
    for (const [name, ws] of Object.entries(r.writers)) if (ws.length) writers[name] = ws;
  }
  const doc = {
    description: 'GENERATED by hooks/dispatch/build-hooks-json.js — do not edit. Modules in one lane run one after another; lanes run in parallel (see dispatch/lanes.js).',
    lanes,
    writers,
  };
  return `${JSON.stringify(doc, null, 2)}\n`;
}

if (require.main === module) {
  const files = [[HOOKS_JSON, expectedText()], [LANES_JSON, expectedLanesText()]];
  if (process.argv.includes('--check')) {
    let stale = false;
    for (const [file, want] of files) {
      let have = '';
      try { have = fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n'); } catch { /* missing */ }
      if (have !== want) { stale = true; process.stderr.write(`${path.basename(file)} is stale\n`); }
    }
    if (stale) {
      process.stderr.write('run: node plugins/devops/hooks/dispatch/build-hooks-json.js\n');
      process.exit(1);
    }
    process.stdout.write('hooks.json and lanes.json are current\n');
  } else {
    for (const [file, want] of files) {
      fs.writeFileSync(file, want);
      process.stdout.write(`wrote ${file}\n`);
    }
  }
}

module.exports = {
  build, serialize, expectedText, expectedLanesText, dispatcherCommand, HOOKS_JSON, LANES_JSON, MANIFEST, DEFAULT_TIMEOUT_S, HEADROOM_S,
};
