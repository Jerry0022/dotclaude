#!/usr/bin/env node
'use strict';
/**
 * @script home-backup
 * @version 0.1.0
 * @plugin devops
 * @description Opt-in backup of the allowlisted part of ~/.claude (settings,
 *   agents, own skills/commands, memory, scripts) to a PRIVATE GitHub repo.
 *   The daily run is pure node on the OS scheduler — zero model tokens.
 *
 *   Safety model, strictest first: (1) the generated .gitignore is
 *   deny-by-default; (2) a code-level denylist unstages secret-looking paths
 *   even if the .gitignore was edited; (3) symlinks/junctions are never
 *   staged; (4) every staged file is scanned for secrets and private data
 *   (lib/backup-scan.js) — any hit unstages everything, writes a report with
 *   file+line+rule (never values), notifies, and nothing is committed or
 *   pushed. Commits use a fixed local identity, never the user's e-mail.
 *
 *   Runbook: deep-knowledge/home-backup.md.
 *
 * Usage:
 *   home-backup.js setup --repo <owner>/<name>   one-time setup, idempotent
 *   home-backup.js run                           the scheduled job
 *   home-backup.js scan                          dry run of both scans
 *   home-backup.js status                        switches, job, last result
 *   home-backup.js disable                       unregister job, switch off
 *   home-backup.js render-gitignore              print the .gitignore
 *
 * Exit codes:
 *   0  ok (also: disabled, or nothing changed)
 *   1  blocked by a scan hit, or a git/gh/scheduler step failed
 *   2  usage error
 */

const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawnSync } = require('child_process');
const config = require('../hooks/lib/devops-config');
const scheduler = require('./lib/scheduler');
const desktopNotify = require('./lib/desktop-notify');
const backupScan = require('./lib/backup-scan');

const JOB_NAME = 'home-backup';
const JOB_TIME = '12:30';
const REPORT_JSON = 'home-backup-report.json';
const REPORT_TXT = 'home-backup-report.txt';
const LOG_FILE = 'home-backup.log';
const LOG_KEEP = 50;
const BRANCH = 'main';
const IDENTITY = Object.freeze({ name: 'claude-home-backup', email: 'noreply@localhost' });
const GIT_TIMEOUT = 120_000;
const GH_TIMEOUT = 60_000;
const REPO_RE = /^[A-Za-z0-9-]+\/[A-Za-z0-9._-]+$/;

const ALLOWLIST = [
  '.gitignore', '.backupallow', 'CLAUDE.md', 'settings.json', 'settings.local.json', 'keybindings.json',
  'output-styles/', 'agents/', 'skills/', 'commands/', 'scripts/', 'projects/',
  'statusline*.js', 'statusline*.sh', 'statusline*.ps1', 'delegation.json', 'devops-*.json',
];
const PLUGIN_SYNCED = ['skills/synced/'];
const NEVER_DIRS = [
  'cache', 'plugins', 'file-history', 'shell-snapshots', 'telemetry', 'todos', 'debug', 'logs',
  'backups', 'statsig', 'ide', 'session-env', 'node_modules', '.git',
];
const NEVER_NAME_WORDS = /token|secret|credential/i;
const NEVER_EXT = /(?:\.env|\.jsonl|\.log)$/i;
const OWN_FILES = [REPORT_JSON, REPORT_TXT, LOG_FILE];

/** The deny-by-default .gitignore for ~/.claude. */
function renderGitignore() {
  const lines = [
    '# Generated by devops home-backup — deny by default, then an explicit allowlist.',
    '/*',
    ...ALLOWLIST.map((p) => `!/${p}`),
    '/projects/*/*',
    '!/projects/*/memory/',
    ...PLUGIN_SYNCED.map((p) => `/${p}`),
    '',
    '# Never — these win over everything above.',
    '.credentials.json',
    '**/*token*',
    '**/*secret*',
    '**/*credential*',
    '**/*.env',
    '**/.env',
    'devops-api.env',
    '*.jsonl',
    '*.log',
    'history.jsonl',
    'edge-*-profile*/',
    ...NEVER_DIRS.filter((d) => d !== '.git').map((d) => `${d}/`),
    ...OWN_FILES.map((f) => `/${f}`),
    '',
  ];
  return lines.join('\n');
}

/** Code-level denylist (defence in depth): true when `rel` must never be staged. */
function isDenied(rel) {
  const parts = rel.replace(/\\/g, '/').split('/');
  const name = parts[parts.length - 1];
  if (parts.length === 1 && (name === '.credentials.json' || OWN_FILES.includes(name))) return true;
  if (name === '.credentials.json' || name === 'devops-api.env' || name === 'history.jsonl') return true;
  if (NEVER_NAME_WORDS.test(name) || NEVER_EXT.test(name) || name === '.env') return true;
  return parts.slice(0, -1).some((seg) => NEVER_DIRS.includes(seg) || /^edge-.*-profile/.test(seg) || NEVER_NAME_WORDS.test(seg));
}

function defaultRun(cmd, args, opts = {}) {
  const r = spawnSync(cmd, args, {
    cwd: opts.cwd,
    input: opts.input,
    encoding: opts.encoding === 'buffer' ? undefined : 'utf8',
    timeout: opts.timeout || GIT_TIMEOUT,
    windowsHide: true,
    maxBuffer: 512 * 1024 * 1024,
    env: { ...process.env, GIT_TERMINAL_PROMPT: '0', ...opts.env },
  });
  const text = (v) => (v == null ? '' : Buffer.isBuffer(v) ? v.toString('utf8') : String(v));
  return {
    status: r.status,
    stdout: opts.encoding === 'buffer' ? (r.stdout || Buffer.alloc(0)) : text(r.stdout),
    stderr: text(r.stderr) || (r.error ? String(r.error.message) : ''),
  };
}

function makeContext(opts = {}) {
  return {
    home: opts.home || os.homedir(),
    run: opts.run || defaultRun,
    platform: opts.platform || process.platform,
    now: opts.now || (() => new Date()),
    notify: opts.notify || ((msg) => desktopNotify.notify(msg, { platform: opts.platform })),
  };
}

const claudeDir = (ctx) => path.join(ctx.home, '.claude');
const inClaude = (ctx, name) => path.join(claudeDir(ctx), name);
const schedulerIo = (ctx) => ({ platform: ctx.platform, run: ctx.run });

function git(ctx, args, extra = {}) {
  return ctx.run('git', args, { cwd: claudeDir(ctx), timeout: GIT_TIMEOUT, ...extra });
}

function gh(ctx, args) {
  return ctx.run('gh', args, { cwd: ctx.home, timeout: GH_TIMEOUT });
}

function readSettings(ctx) {
  return config.load(ctx.home, { home: ctx.home }).values.homeBackup;
}

function oneLine(s, n = 160) {
  const v = String(s || '').replace(/\s+/g, ' ').trim();
  return v.length > n ? `${v.slice(0, n - 1)}…` : v;
}

function appendLog(ctx, status, detail = '') {
  try {
    const file = inClaude(ctx, LOG_FILE);
    const old = fs.existsSync(file) ? fs.readFileSync(file, 'utf8').split('\n').filter(Boolean) : [];
    old.push(`${ctx.now().toISOString()} ${status}${detail ? ` ${detail}` : ''}`);
    fs.writeFileSync(file, `${old.slice(-LOG_KEEP).join('\n')}\n`);
  } catch { /* the log is a convenience */ }
}

function lastLogLine(ctx) {
  try {
    const lines = fs.readFileSync(inClaude(ctx, LOG_FILE), 'utf8').split('\n').filter(Boolean);
    return lines[lines.length - 1] || null;
  } catch {
    return null;
  }
}

function clearReport(ctx) {
  for (const f of [REPORT_JSON, REPORT_TXT]) fs.rmSync(inClaude(ctx, f), { force: true });
}

function writeReport(ctx, kind, message, hits = []) {
  const report = { generatedAt: ctx.now().toISOString(), kind, message, hits };
  const txt = [
    `Home-Backup ${kind === 'blocked' ? 'blockiert' : 'fehlgeschlagen'}: ${message}`,
    '',
    ...hits.map((h) => `${h.file}${h.line ? `:${h.line}` : ''}  ${h.rule}`),
    '',
    'Werte werden nie gespeichert. Entfernen/schwärzen oder bewusst in ~/.claude/.backupallow erlauben.',
    '',
  ].join('\n');
  fs.mkdirSync(claudeDir(ctx), { recursive: true });
  fs.writeFileSync(inClaude(ctx, REPORT_JSON), `${JSON.stringify(report, null, 2)}\n`);
  fs.writeFileSync(inClaude(ctx, REPORT_TXT), txt);
}

function chunked(list, size = 100) {
  const out = [];
  for (let i = 0; i < list.length; i += size) out.push(list.slice(i, i + size));
  return out;
}

function pathHasSymlink(ctx, rel) {
  let cur = claudeDir(ctx);
  for (const seg of rel.split('/')) {
    cur = path.join(cur, seg);
    try {
      if (fs.lstatSync(cur).isSymbolicLink()) return true;
    } catch {
      return false;
    }
  }
  return false;
}

/** Staged `[{status, file}]` from the index, renames split into delete + add. */
function stagedEntries(ctx) {
  const r = git(ctx, ['diff', '--cached', '--name-status', '--no-renames', '-z']);
  if (r.status !== 0) throw new Error(`git diff --cached failed: ${oneLine(r.stderr)}`);
  const tok = r.stdout.split('\0');
  const entries = [];
  for (let i = 0; i + 1 < tok.length; i += 2) entries.push({ status: tok[i], file: tok[i + 1] });
  return entries;
}

function unstage(ctx, files) {
  for (const group of chunked(files)) git(ctx, ['reset', '-q', '--', ...group]);
}

/** `git add -A`, then drop denylisted and symlinked paths; returns the final staged entries. */
function stage(ctx) {
  const add = git(ctx, ['add', '-A']);
  if (add.status !== 0) throw new Error(`git add failed: ${oneLine(add.stderr)}`);
  let entries = stagedEntries(ctx);
  const refused = entries
    .filter((e) => e.status !== 'D' && (isDenied(e.file) || pathHasSymlink(ctx, e.file)))
    .map((e) => e.file);
  if (refused.length) {
    unstage(ctx, refused);
    entries = entries.filter((e) => !refused.includes(e.file));
  }
  return entries;
}

function loadAllow(ctx) {
  try {
    return backupScan.parseAllow(fs.readFileSync(inClaude(ctx, '.backupallow'), 'utf8'));
  } catch {
    return backupScan.parseAllow('');
  }
}

/** Index blobs of `files` as `Map<file, Buffer|null>` via one `git cat-file --batch`. */
function readIndexBlobs(ctx, files) {
  const blobs = new Map();
  const names = files.filter((f) => !f.includes('\n'));
  files.filter((f) => f.includes('\n')).forEach((f) => blobs.set(f, null));
  if (!names.length) return blobs;
  const r = git(ctx, ['cat-file', '--batch'], { input: names.map((f) => `:${f}`).join('\n') + '\n', encoding: 'buffer' });
  if (r.status !== 0) throw new Error(`git cat-file failed: ${oneLine(r.stderr)}`);
  const buf = r.stdout;
  let pos = 0;
  for (const file of names) {
    const eol = buf.indexOf(10, pos);
    const header = buf.toString('utf8', pos, eol).split(' ');
    pos = eol + 1;
    if (header[1] !== 'blob') { blobs.set(file, null); continue; }
    const size = Number(header[2]);
    blobs.set(file, buf.subarray(pos, pos + size));
    pos += size + 1;
  }
  return blobs;
}

function scanBlobs(blobs, allow) {
  const hits = [];
  for (const [file, buf] of blobs) {
    if (buf === null) hits.push({ file, line: 0, rule: backupScan.UNSCANNABLE });
    else hits.push(...backupScan.scanBuffer(file, buf, allow));
  }
  return hits;
}

/** Files a dry run would consider: tracked + untracked, ignore rules and denylist applied. */
function candidateFiles(ctx) {
  const r = git(ctx, ['ls-files', '-z', '--cached', '--others', '--exclude-standard']);
  if (r.status !== 0) throw new Error(`git ls-files failed: ${oneLine(r.stderr)}`);
  return [...new Set(r.stdout.split('\0').filter(Boolean))]
    .filter((f) => !isDenied(f) && !pathHasSymlink(ctx, f) && fs.existsSync(path.join(claudeDir(ctx), f)));
}

function scanWorkingTree(ctx, files, allow) {
  const hits = [];
  for (const file of files) {
    hits.push(...backupScan.scanBuffer(file, fs.readFileSync(path.join(claudeDir(ctx), file)), allow));
  }
  return hits;
}

function currentBranch(ctx) {
  const r = git(ctx, ['symbolic-ref', '--short', 'HEAD']);
  return r.status === 0 && r.stdout.trim() ? r.stdout.trim() : BRANCH;
}

function hasUnpushedCommits(ctx) {
  if (git(ctx, ['rev-parse', '--verify', '-q', 'HEAD']).status !== 0) return false;
  const r = git(ctx, ['rev-list', '--count', `origin/${currentBranch(ctx)}..HEAD`]);
  return r.status !== 0 || Number(r.stdout.trim()) > 0;
}

function push(ctx) {
  return git(ctx, ['push', '-q', '-u', 'origin', currentBranch(ctx)]);
}

function fail(ctx, stage_, message) {
  writeReport(ctx, 'error', `${stage_}: ${message}`);
  appendLog(ctx, 'error', stage_);
  ctx.notify({ title: 'Home-Backup', body: `Home-Backup fehlgeschlagen (${stage_}) — siehe ~/.claude/${REPORT_TXT}` });
  return { code: 1, status: 'error', lines: [`home-backup: ${stage_} failed: ${message}`] };
}

/** The scheduled job. Silent unless something needs attention. */
function runBackup(opts = {}) {
  const ctx = makeContext(opts);
  if (!readSettings(ctx).enabled) return { code: 0, status: 'disabled', lines: [] };
  if (!fs.existsSync(inClaude(ctx, '.git'))) return fail(ctx, 'setup', 'no git repo in ~/.claude — run setup');

  let entries;
  try {
    entries = stage(ctx);
  } catch (e) {
    return fail(ctx, 'stage', e.message);
  }

  if (entries.length === 0) {
    if (hasUnpushedCommits(ctx)) {
      const p = push(ctx);
      if (p.status !== 0) return fail(ctx, 'push', oneLine(p.stderr));
      appendLog(ctx, 'pushed-pending');
    } else {
      appendLog(ctx, 'unchanged');
    }
    clearReport(ctx);
    return { code: 0, status: 'unchanged', lines: [] };
  }

  let hits;
  try {
    hits = scanBlobs(readIndexBlobs(ctx, entries.filter((e) => e.status !== 'D').map((e) => e.file)), loadAllow(ctx));
  } catch (e) {
    git(ctx, ['reset', '-q']);
    return fail(ctx, 'scan', e.message);
  }
  if (hits.length) {
    git(ctx, ['reset', '-q']);
    writeReport(ctx, 'blocked', `${hits.length} Funde`, hits);
    appendLog(ctx, 'blocked', `${hits.length} hits`);
    ctx.notify({ title: 'Home-Backup', body: `Home-Backup blockiert: ${hits.length} Funde — siehe ~/.claude/${REPORT_TXT}` });
    return { code: 1, status: 'blocked', hits, lines: [`home-backup: blocked, ${hits.length} hits — see ~/.claude/${REPORT_TXT}`] };
  }

  const stamp = ctx.now().toISOString();
  const commit = git(ctx, ['commit', '-q', '--no-verify', '-m', `backup: ${stamp}`], {
    env: {
      GIT_AUTHOR_NAME: IDENTITY.name, GIT_AUTHOR_EMAIL: IDENTITY.email,
      GIT_COMMITTER_NAME: IDENTITY.name, GIT_COMMITTER_EMAIL: IDENTITY.email,
    },
  });
  if (commit.status !== 0) {
    git(ctx, ['reset', '-q']);
    return fail(ctx, 'commit', oneLine(commit.stderr || commit.stdout));
  }
  const p = push(ctx);
  if (p.status !== 0) return fail(ctx, 'push', oneLine(p.stderr));

  clearReport(ctx);
  appendLog(ctx, 'pushed', `${entries.length} files`);
  return { code: 0, status: 'pushed', files: entries.length, lines: [] };
}

/** Dry run of both scans over what a run would stage. */
function scanDryRun(opts = {}) {
  const ctx = makeContext(opts);
  if (!fs.existsSync(inClaude(ctx, '.git'))) {
    return { code: 1, status: 'error', lines: ['home-backup: no git repo in ~/.claude — run setup first'] };
  }
  let hits;
  try {
    const files = candidateFiles(ctx);
    hits = scanWorkingTree(ctx, files, loadAllow(ctx));
    if (!hits.length) return { code: 0, status: 'clean', hits, lines: [`${files.length} files scanned, no hits`] };
  } catch (e) {
    return { code: 1, status: 'error', lines: [`home-backup: ${e.message}`] };
  }
  return {
    code: 1, status: 'hits', hits,
    lines: hits.map((h) => `${h.file}${h.line ? `:${h.line}` : ''}  ${h.rule}`),
  };
}

function normalizeRemote(url) {
  return String(url).trim().replace(/\.git$/, '').replace(/\/$/, '').toLowerCase();
}

function remoteUrl(repo) {
  return `https://github.com/${repo}.git`;
}

function ensureRepoExists(ctx, repo) {
  const view = gh(ctx, ['repo', 'view', repo, '--json', 'isPrivate', '-q', '.isPrivate']);
  if (view.status === 0) {
    if (view.stdout.trim() !== 'true') return `repo ${repo} exists but is not private — refusing to back up into it`;
    return null;
  }
  const create = gh(ctx, ['repo', 'create', repo, '--private', '--description', 'Claude Code home backup (devops plugin)']);
  return create.status === 0 ? null : `gh repo create failed: ${oneLine(create.stderr)}`;
}

function ensureLocalRepo(ctx, repo) {
  fs.mkdirSync(claudeDir(ctx), { recursive: true });
  const url = remoteUrl(repo);
  if (!fs.existsSync(inClaude(ctx, '.git'))) {
    const init = git(ctx, ['init', '-q', '-b', BRANCH]);
    if (init.status !== 0) return `git init failed: ${oneLine(init.stderr)}`;
  }
  const origin = git(ctx, ['remote', 'get-url', 'origin']);
  if (origin.status !== 0) {
    const add = git(ctx, ['remote', 'add', 'origin', url]);
    return add.status === 0 ? null : `git remote add failed: ${oneLine(add.stderr)}`;
  }
  if (normalizeRemote(origin.stdout) !== normalizeRemote(url)) {
    return `~/.claude is already a git repo with origin ${oneLine(origin.stdout, 100)} — refusing to touch it`;
  }
  return git(ctx, ['remote', 'set-url', 'origin', url]).status === 0 ? null : 'git remote set-url failed';
}

/** One-time, idempotent setup; ends with the first run. */
function setup(opts = {}) {
  const ctx = makeContext(opts);
  const repo = opts.repo;
  const stop = (msg) => ({ code: 1, status: 'error', lines: [`home-backup setup: ${msg}`] });
  if (!REPO_RE.test(repo || '')) return stop('--repo <owner>/<name> required');

  if (gh(ctx, ['auth', 'status']).status !== 0) return stop('gh is not authenticated — run `gh auth login` first');
  const repoProblem = ensureRepoExists(ctx, repo);
  if (repoProblem) return stop(repoProblem);
  const localProblem = ensureLocalRepo(ctx, repo);
  if (localProblem) return stop(localProblem);

  fs.writeFileSync(inClaude(ctx, '.gitignore'), renderGitignore());

  const job = scheduler.registerJob({
    name: JOB_NAME,
    schedule: { kind: 'daily', time: JOB_TIME },
    command: [process.execPath, path.resolve(__filename), 'run'],
  }, schedulerIo(ctx));
  if (!job.ok) return stop(`could not register the daily job: ${job.detail}`);

  config.setValue('homeBackup.repo', repo, 'global', ctx.home, { home: ctx.home });
  config.setValue('homeBackup.enabled', true, 'global', ctx.home, { home: ctx.home });

  const first = runBackup(opts);
  const lines = [
    `home-backup: repo ${repo}, daily job ${JOB_NAME} at ${JOB_TIME} (${job.method})`,
    `first run: ${first.status}`,
    ...first.lines,
  ];
  return { code: first.code, status: first.status, lines };
}

function disable(opts = {}) {
  const ctx = makeContext(opts);
  const job = scheduler.unregisterJob(JOB_NAME, schedulerIo(ctx));
  config.setValue('homeBackup.enabled', false, 'global', ctx.home, { home: ctx.home });
  const lines = [
    job.ok ? 'home-backup: daily job removed, backup switched off' : `home-backup: switched off, but the job could not be removed: ${job.detail}`,
    'The private repo and ~/.claude/.git are left in place (delete them yourself if wanted).',
  ];
  return { code: job.ok ? 0 : 1, status: 'disabled', lines };
}

function status(opts = {}) {
  const ctx = makeContext(opts);
  const s = readSettings(ctx);
  const registered = scheduler.isRegistered(JOB_NAME, schedulerIo(ctx));
  const last = lastLogLine(ctx);
  const report = fs.existsSync(inClaude(ctx, REPORT_TXT));
  const lines = [
    `enabled: ${s.enabled}`,
    `repo: ${s.repo || '(none)'}`,
    `job registered: ${registered === null ? 'unknown' : registered}`,
    `last run: ${last || '(none)'}`,
    ...(report ? [`open report: ~/.claude/${REPORT_TXT}`] : []),
  ];
  return { code: 0, status: 'ok', settings: s, registered, last, lines };
}

function parseArgs(argv) {
  const [command, ...rest] = argv;
  const out = { command };
  for (let i = 0; i < rest.length; i++) {
    if (rest[i] === '--repo') out.repo = rest[++i];
  }
  return out;
}

function main(argv = process.argv.slice(2)) {
  const args = parseArgs(argv);
  const handlers = {
    setup: () => setup({ repo: args.repo }),
    run: () => runBackup(),
    scan: () => scanDryRun(),
    status: () => status(),
    disable: () => disable(),
    'render-gitignore': () => ({ code: 0, lines: [renderGitignore().trimEnd()] }),
  };
  const handler = handlers[args.command];
  if (!handler) {
    process.stderr.write('usage: home-backup.js setup --repo <owner>/<name> | run | scan | status | disable | render-gitignore\n');
    return 2;
  }
  let result;
  try {
    result = handler();
  } catch (e) {
    process.stderr.write(`home-backup: ${oneLine(e.message)}\n`);
    return 1;
  }
  const stream = result.code === 0 ? process.stdout : process.stderr;
  if (result.lines.length) stream.write(`${result.lines.join('\n')}\n`);
  return result.code;
}

if (require.main === module) process.exit(main());

module.exports = {
  JOB_NAME, JOB_TIME, REPORT_JSON, REPORT_TXT, LOG_FILE,
  renderGitignore, isDenied, defaultRun, runBackup, scanDryRun, setup, disable, status, main,
};
